"""会话记忆这一层的提示词：滚动摘要 + 用户画像抽取。"""

SUMMARY_SYSTEM = """你在维护一段多轮对话的长期记忆：把「已有摘要」和「新增对话」合并成一份新摘要。

要求：
1. 保留：用户身份与偏好、已经确认的事实与结论、未完成的事项、关键数字与专有名词
2. 丢弃：寒暄客套、重复内容、已经被推翻的说法
3. 用第三人称陈述（"用户…"、"助手…"），条目化，不超过 400 字
4. 只输出摘要正文，不要任何解释或前后缀"""


def profile_extract_system(current: dict) -> str:
    """用户画像抽取的提示词（current = 当前已知画像，让模型只做增量补充）。

    ⚠️ 画像只是**背景**，不是本轮要回答的议题 —— 下面那句提醒是踩出来的：
    用户问「知识库里有哪些内容？」，画像里写着"当前目标：申请年假"，模型就在结尾补了一句
    "知识库中未找到与年假相关的内容"，而用户根本没问、库里也明明有。
    """
    return (
        "从对话中提取用户信息，只填写有明确依据的字段。\n"
        f"当前已知画像：{current}\n"
        "如果没有新信息，hasInfo 返回 false。\n"
        "（这些信息只作为后续对话的背景，不要据此主动补充用户没问的话题，"
        "也不要因为资料里没有它提到的话题就声明\"知识库中未找到相关内容\"。）"
    )



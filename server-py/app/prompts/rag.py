"""知识库（RAG）这一层的提示词：检索问答、重排打分、意图判定、元数据预填。"""

# 旧版"参考文档 + 问题"式的知识库问答提示词（rag_answer_stream 用）
RAG_SYSTEM = """你是 WorkMind AI 知识库助手。

规则：
1. 只根据下方提供的参考文档回答问题，不使用文档之外的知识
2. 如果文档中没有相关内容，明确说"知识库中未找到相关内容"
3. 回答要准确、简洁，必要时列出要点
4. 引用资料时，在句末直接标注方括号编号，例如 [1] 或 [1][3]——
   编号就是资料列表里的序号，**不要写"【来源：文档标题 · 第N页】"这种长句**"""

# 重排打分：判据是"这段能不能**直接回答**这个查询"，不是"像不像"。
# 标度 0-10：9-10 直接含答案，6-8 强相关，3-5 主题沾边但答不了，0-2 无关。
RERANK_SYSTEM = """你是检索结果重排器。给定一个查询和若干候选片段，判断**每条片段能否直接回答这个查询**。

打分标准（0-10）：
- 9-10：直接包含答案，照它就能回答
- 6-8：强相关，包含答案的大部分要素
- 3-5：主题沾边，但不回答这个具体问题
- 0-2：无关

只按"能否回答该查询"打分，不要因为片段本身写得详细就打高分。
必须给每个候选都打分，编号与输入一致。"""

# 消息**分类**（hybrid 模式下，只有"没有知识信号"的消息才走这一步）。
#
# 为什么分类提示词问的是"属于哪一类"，而不是"该不该查库"：
# 模型不知道公司库里有什么，让它直接判"要不要检索"必然出错 —— 历史坑就是它对
# 「rag召回失败」说"这属于通用技术问答、无需检索"，而库里正好有那篇 RAG 资料。
# 改成让模型只回答"这句话是哪一类"，**类别 → 是否检索交给代码做确定性映射**
# （见 rag/intent.py 的 _CATEGORY_POLICY）：泛化能力用上了，判断权还在代码手里。
INTENT_CATEGORY_SYSTEM = """你是消息分类器。把用户这一句话分到下面六类之一，只输出 JSON：{"category": "...", "reason": "一句话依据"}。

- chitchat：打招呼、客套、闲聊、讲笑话、写诗
- memory：问对话记忆或助手自身（你记得吗 / 我叫什么 / 我们刚聊到哪 / 你是谁 / 上次说的那个）
- self_intro：用户在自我介绍（我叫X / 我是某部门的）
- action：要求助手执行具体动作（发通知、算数、查日期、生成报告、订会议室）
- company：可能涉及公司内部制度、流程、规定、内部资料、公司产品的问题
- general：通用知识或常识问题（技术栈怎么选、行业常识，与公司规定无关）

拿不准是不是公司内部资料就选 company。"""


def finalize_system(dsml_mark: str) -> str:
    """步数用尽后的收尾提示词。dsml_mark = DeepSeek 误当正文吐出来的工具调用标记。"""
    return f"""本轮的工具调用次数已用尽，工具现在不可用。

请直接给出最终回答，不要再要求调用任何工具：
1. 用中文回答，先把**已经拿到的信息**整理清楚（带上来源或时间，便于用户核对）
2. 明确区分「已查到的」和「没查到的」，没查到的如实说明缺什么
3. 不要再重复搜索、不要再编造；不确定的地方就说 不确定
4. 如果任务要求报告或总结，直接输出正文
5. 绝对不要输出任何工具调用格式或标记（例如 {dsml_mark} 这种），那会被当成乱码展示给用户"""



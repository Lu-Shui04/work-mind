    "那是**之前某一轮**的检索结论（当时可能没检索到，或者问的根本是另一个问题），对本轮无效。"
    "只要本轮资料里有答案，就必须直接答出来并标注编号，严禁把上文那句\"没查到\"复述成本轮结论。\n"
    "5. ⚠️ **只回答用户本轮问的那个问题**：不要主动补充用户没问的话题，更不要对没问的话题"
